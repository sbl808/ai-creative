import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import { clientStorageScript } from '../worker/src/frontend/storage/client-storage.js';
import { ACTIONS_SCRIPT } from '../worker/src/frontend/studios/story/actions.js';
import { HELPERS_SCRIPT } from '../worker/src/frontend/studios/story/helpers.js';
import { renderStudioShell } from '../worker/src/frontend/shared.js';

const source = clientStorageScript();
assert.match(source, /indexedDB\.open\('aics_creations_v1', 7\)/);
assert.match(source, /createObjectStore\('studio_handoffs'/);
assert.match(source, /window\.AICS_HANDOFFS\s*=\s*\{/);
assert.match(source, /contractVersion!==1/);
assert.match(source, /owner_target_createdAt/);
new vm.Script(source, { filename: 'client-storage.js' });
new vm.Script(ACTIONS_SCRIPT, { filename: 'story-actions.js' });

const storyShell = renderStudioShell({ id: 'story', activeId: 'story', steps: [] });
const storyRestoreGuard = storyShell.indexOf('if (SHELL_ID === "story")');
const storyLegacyRead = storyShell.indexOf('localStorage.getItem(draftKey)', storyRestoreGuard);
assert.ok(storyRestoreGuard >= 0, 'Shared Shell skips generic restore for Story');
assert.ok(storyLegacyRead > storyRestoreGuard, 'Story legacy localStorage restore is bypassed before the generic read');
assert.match(HELPERS_SCRIPT, /studioMigrateLegacyStorage\(\);/, 'Story helpers own legacy migration');
assert.match(ACTIONS_SCRIPT, /var storyResetInProgress=false;/);
assert.match(ACTIONS_SCRIPT, /function autoSave\(\)\{\s*if\(storyResetInProgress\)return Promise\.resolve\(null\);/);
assert.match(ACTIONS_SCRIPT, /function autoSaveImgCache\(\)\{\s*if\(storyResetInProgress\)return Promise\.resolve\(\[\]\);/);
assert.match(ACTIONS_SCRIPT, /window\.studioReset = function studioResetStorySession\(\)/);
assert.match(ACTIONS_SCRIPT, /window\.AICS_SESSIONS\.remove\(storySessionId\)/);
assert.match(ACTIONS_SCRIPT, /localStorage\.removeItem\('aics_draft_story_imgcache'\)/);

const idea = readFileSync(new URL('../worker/src/frontend/ideas.js', import.meta.url), 'utf8');
const story = readFileSync(new URL('../worker/src/frontend/studios/story/actions.js', import.meta.url), 'utf8');
const storyUi = readFileSync(new URL('../worker/src/frontend/studios/story/ui.js', import.meta.url), 'utf8');
const storyPage = readFileSync(new URL('../worker/src/frontend/studios/story/page.js', import.meta.url), 'utf8');
assert.match(idea, /var fullPayload=ideaHandoffPayload\(idea\);/);
assert.match(idea, /window\.AICS_HANDOFFS\.create\(\{contractVersion:1,source:'ideas',target:'story',payload:fullPayload\}\)/);
assert.match(idea, /kind:'idea-workspace',schemaVersion:1,category:generatedBrief/);
assert.match(idea, /location\.href='\/app\/story\?handoff='/);
assert.doesNotMatch(idea, /AICS_SESSIONS/);
assert.doesNotMatch(idea, /if\(studio==='story'\)return \{key:'aics_draft_story'/);
assert.match(storyUi, /id="ideaHandoffPanel"/);
assert.match(storyUi, /id="acceptIdeaHandoffBtn"/);
assert.match(story, /function studioReceiveIdeaHandoff\(\)/);
assert.match(story, /pendingIdeaResult=studioNormalizeIdeaHandoffPayload\(record\.payload\)/);
assert.match(story, /function studioNormalizeIdeaHandoffPayload\(payload\)/);
assert.match(story, /pendingIdeaResult\.fields/);
assert.match(story, /Idea Brief အချက်အလက်/);
assert.match(story, /function studioMapIdeaResultToStoryInput\(idea,fields,category\)/);
assert.match(story, /function studioAcceptIdeaHandoff\(\)/);
assert.match(storyUi, /data-aics-action="accept-story-idea-handoff"/);
assert.match(storyPage, /case 'accept-story-idea-handoff':window\.studioAcceptIdeaHandoff\(\)/);
assert.match(story, /AICS_SESSIONS\.create\(\{studio:'STORY'/);
assert.match(story, /studioRestoreDraft\(nextDraft\)/);
assert.match(story, /AICS_HANDOFFS\.remove\(handoffId\)/);
const receiverStart = story.indexOf('function studioReceiveIdeaHandoff');
const acceptStart = story.indexOf('function studioAcceptIdeaHandoff');
assert.ok(receiverStart >= 0 && acceptStart > receiverStart, 'receiver must be defined before the explicit accept action');
const receiverSource = story.slice(receiverStart, acceptStart);
assert.doesNotMatch(receiverSource, /studioRestoreDraft|autoSave|AICS_SESSIONS\.create/);
console.log('IndexedDB Studio Handoff tests passed.');
